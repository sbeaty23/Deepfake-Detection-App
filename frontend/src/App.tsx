import { useState } from 'react'
import { useEffect } from 'react';
import './App.css'

const MAX_FILE_SIZE = 5 * 1024 ** 2;
const ALLOWED_TYPES = [
  "image/jpeg",
  "image/png",
  "image/webp"
];

function App() {
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [previewUrl, setPreviewUrl] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    console.log("It works!");

    return () => {
      if(previewUrl !== null)
        URL.revokeObjectURL(previewUrl);
    };
  }, [previewUrl]);

  function handleFileChange(
    event: React.ChangeEvent<HTMLInputElement>
  ){
    const file = event.target.files?.[0]

    if(!file){
      handleError("Please upload an image file.");
      return;
    }

    if(!ALLOWED_TYPES.includes(file.type)){
      handleError("Please upload an image file.");
      return;
    }
    
    if(file.size > MAX_FILE_SIZE){
      handleError("File is too large.");
      return;
    }

    setError(null);
    setSelectedFile(file);
    const url = URL.createObjectURL(file);
    setPreviewUrl(url);
  }
  
  function handleError(message: string){
    setError(message);
    setPreviewUrl(null);
    setSelectedFile(null);
  }
  return (
      <main>
        <h1>Deepfake Detection App</h1>
        <h3>See whether or not an image was generated by AI</h3>
        <p>Upload an image to determine whether it was AI-Generated</p>
        {/* <button type="button">Upload Image</button> */}
        <input 
        type="file" 
        accept="image/jpeg,image/png,image/webp" 
        onChange={handleFileChange}
        />
        {previewUrl && (
          <img src={previewUrl} alt="Selected image" />
        )}
        {error && <p role="alert">{error}</p>}
      </main>
    );
}


export default App
