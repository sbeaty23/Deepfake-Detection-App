import { useState } from 'react'
import { useEffect } from 'react';
import './App.css'

const MAX_FILE_SIZE = 5 * 1024 ** 2;
const ALLOWED_TYPES = [
  "image/jpeg",
  "image/png",
  "image/webp"
];

function App() {
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [previewUrl, setPreviewUrl] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const [result, setResult] = useState<string | null>(null);
  const [isAnalyzing, setIsAnalyzing] = useState(false);

  useEffect(() => {
    console.log("It works!");

    return () => {
      if(previewUrl !== null)
        URL.revokeObjectURL(previewUrl);
    };
  }, [previewUrl]);

  function handleFileChange(
    event: React.ChangeEvent<HTMLInputElement>
  ){
    const file = event.target.files?.[0]

    if(!file){
      handleError("Please upload an image file.");
      return;
    }

    if(!ALLOWED_TYPES.includes(file.type)){
      handleError("Please upload an image file.");
      return;
    }
    
    if(file.size > MAX_FILE_SIZE){
      handleError("File is too large.");
      return;
    }

    setError(null);
    setSelectedFile(file);
    const url = URL.createObjectURL(file);
    setPreviewUrl(url);
  }
  
  function handleError(message: string){
    setError(message);
    setPreviewUrl(null);
    setSelectedFile(null);
  }

  //Function that connects to the backeend
  async function handleAnalyze() {
    if (!selectedFile) {
      setError("Please upload an image first.");
      return;
    }

    setIsAnalyzing(true);
    setError(null);
    setResult(null);

    // Prepare the selected file for the Python backend
    const formData = new FormData();
    formData.append("image", selectedFile);

    try {
      const response = await fetch(
        "http://127.0.0.1:8000/api/analyze",
        {
          method: "POST",
          body: formData,
        }
      );

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          data.detail || "Image upload failed."
        );
      }

      setResult(data.message);
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Could not connect to the backend."
      );
    } finally {
      setIsAnalyzing(false);
    }
  }

  return (
      <main>
        <h1>Deepfake Detection App</h1>
        <h3>See whether or not an image was generated by AI</h3>
        <p>Upload an image to determine whether it was AI-Generated</p>
        {/* <button type="button">Upload Image</button> */}
        <input 
        type="file" 
        accept="image/jpeg,image/png,image/webp" 
        onChange={handleFileChange}
        />
        {previewUrl && (
          <img src={previewUrl} alt="Selected image" />
        )}

        {/*Analyzye button*/}
        {selectedFile && (
          <button
            type="button"
            onClick={handleAnalyze}
            disabled={isAnalyzing}
          >
            {isAnalyzing ? "Uploading..." : "Analyze Image"}
          </button>
        )}

        {result && (
          <p style={{ color: "green" }} role="status">
            {result}
          </p>
        )}
        {error && <p role="alert">{error}</p>}
      </main>
    );
}


export default App
